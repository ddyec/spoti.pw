#!/usr/bin/env python3
"""Generate the compiled Chinese catalogue; --check validates committed output."""
import json
from pathlib import Path
import re
import sys
root = Path(__file__).resolve().parents[1]
source = root / 'localization/zh-Hans.json'

def unique(pairs):
    result = {}
    for key, value in pairs:
        assert key not in result, f'Duplicate translation: {key}'
        result[key] = value
    return result

catalog = json.loads(source.read_text(), object_pairs_hook=unique)
formats = re.compile(r'%(?:\d+\$)?(?:\.\d+)?(?:ll|l|z)?[@diufsg%]')
for key, value in catalog.items():
    assert key and value.strip(), f'Empty translation: {key}'
    assert formats.findall(key) == formats.findall(value), f'Format arguments changed: {key}'
quote = lambda text: '@' + json.dumps(text, ensure_ascii=False)
output = '// Generated by scripts/generate-localization.py; edit localization/zh-Hans.json.\n'
output += ''.join(f'            {quote(key)}: {quote(value)},\n' for key, value in sorted(catalog.items()))
target = root / 'tweak/Sources/Core/SGChinese.inc'
if '--check' in sys.argv:
    assert target.read_text() == output, 'Chinese catalogue needs regeneration'
else:
    target.write_text(output)
print(f'Chinese catalogue: {len(catalog)} entries; format placeholders preserved')
